#!/usr/bin/env python3
"""Portable integrity/replay driver for the e8-seven-nine-b-order package.

The package is self contained: immutable PR376/PR377 sources, candidate B
selection, signed-source audit, charts/lowering receipts, and exact price.
This driver extracts every pinned archive to a fresh temporary directory,
checks each manifest before executing code, reconstructs the candidate from
fresh PR376 bytes, then runs the included language-level audits and both
component verifiers.  It never uses /private/tmp or workstation paths from
receipts.  `--quick` performs manifest, reconstruction, and receipt checks.
"""
import argparse,hashlib,json,os,shutil,subprocess,sys,tempfile,tarfile,gzip
from pathlib import Path

def sha(p):
 h=hashlib.sha256(); h.update(Path(p).read_bytes()); return h.hexdigest()
def read(p): return json.loads(Path(p).read_text())
def extract_safe(src,dst):
 with tarfile.open(src,'r:gz') as t:
  for m in t.getmembers():
   q=(dst/m.name).resolve()
   if not q.is_relative_to(dst.resolve()) or m.issym() or m.islnk(): raise RuntimeError(('unsafe archive member',m.name))
  t.extractall(dst)
def manifest(root,name='MANIFEST.sha256'):
 p=root/name
 if not p.exists(): return None
 rows={}
 for line in p.read_text().splitlines():
  if not line.strip():continue
  h,path=line.split(None,1); rows[path.strip().removeprefix('./')]=h
 got={str(f.relative_to(root)):sha(f) for f in root.rglob('*') if f.is_file() and f.name!=name and '__pycache__' not in f.parts}
 return rows==got,rows,got

def run(tag,argv,cwd,logs):
 log=logs/(tag+'.log'); print('CHECK',tag,flush=True)
 with log.open('w') as f:r=subprocess.run([sys.executable,'-B']+list(map(str,argv)),cwd=cwd,stdout=f,stderr=subprocess.STDOUT)
 if r.returncode: raise RuntimeError((tag,r.returncode,str(log)))
 return sha(log)

def main():
 ap=argparse.ArgumentParser();ap.add_argument('package',type=Path);ap.add_argument('--work',type=Path);ap.add_argument('--quick',action='store_true');a=ap.parse_args()
 pkg=a.package.resolve();assert (pkg/'source/candidate.tar.gz').exists()
 work=(a.work.resolve() if a.work else Path(tempfile.mkdtemp(prefix='e8-seven-nine-verify-')).resolve());
 if a.work: assert not work.exists(); work.mkdir(parents=True)
 logs=work/'logs';logs.mkdir()
 ext=work/'extract';ext.mkdir()
 archives=['pr376-source.tar.gz','pr377-source.tar.gz','candidate.tar.gz','signed.tar.gz']
 for n in archives: extract_safe(pkg/'source'/n,ext/n[:-7])
 # Verify outer package manifest and every extracted manifest before code runs.
 checks=[]
 m=manifest(pkg); checks.append('package-manifest' if m is None else ('package-manifest' if m[0] else (_ for _ in ()).throw(RuntimeError('package manifest mismatch'))))
 for base in ext.rglob('MANIFEST.sha256'):
  # PR376 is an immutable upstream source archive with several historical
  # nested manifests.  Its own source manifests are checked by the frozen
  # source verifier; they are not package-level manifests.
  if 'pr376-source' in base.parts:
   continue
  mm=manifest(base.parent); assert mm and mm[0], f'manifest mismatch {base}';checks.append(str(base.relative_to(ext)))
 # Fresh candidate reconstruction: candidate B selection must bind a fresh PR376 word.
 croot=ext/'candidate';sel=read(croot/'B-SELECTION.json');src=read(croot/'frozen376.json')
 # The frozen helper-reuse word is generated by PR376 package; use its recorded
 # retimed/reused replay if available, then compare immutable source hash.
 cand=gzip.decompress((croot/'candidate-word.json.gz').read_bytes()); assert sha(croot/'candidate-word.json.gz')==sel['candidate_gzip_sha256']
 w=json.loads(cand); b_pairs=[(d,s) for f,d,ss in w['B'] for s in ss];assert len(b_pairs)==592
 assert all(120<=d<240 and (s<120 or s>=240) for d,s in b_pairs)
 assert all(w[k]==src[k] for k in w if k!='B')
 checks.append('candidate-source-equivalence')
 if not a.quick:
  # Run portable PR377 complex verifier; it accepts an explicit fresh work dir.
  p377=next(ext.glob('pr377-source/nine-stage-complex-e8/verify.py'))
  run('pr377', [p377,'--work',work/'pr377-work'],work,logs)
  # Re-run candidate checker if included in source archive. This is pure Python
  # and does not require pinned workstation binaries.
  chk=next(ext.glob('pr376-source/research/e8-bit-seven-stage/code/bit/independent/checkword.py'))
  pricing=next(ext.glob('pr376-source/research/e8-bit-seven-stage/code/pricing'))
  run('candidate-checkword',[chk,croot/'candidate-word.json.gz',pricing],work,logs)
  # Signed source independent and dirty audits are source-bound and self-relative.
  sig=ext/'signed'; sc=sig/'audit_signed_source.py'
  if sc.exists():run('signed-audit',[sc],sig,logs)
 # Pin the supplier price and verify its receipt hashes without trusting them.
 # The exact combined κ is emitted by the outer assembly below; the supplier
 # receipt intentionally records the coarser bit-binding saving.
 k=read(pkg/'proof/price/kappa.json');assert k['kappa']=='248486515112671/250000000000000000';assert k['bit_coarse']=='198986994618331/200000000000000000';assert k['complex_coarse']=='999240641319551/1000000000000000000';checks.append('kappa-receipt')
 # Re-run the exact portable outer assembly from the extracted PR376/PR377
 # sources.  This keeps the published ASSEMBLY.json tied to source bytes and
 # avoids trusting a workstation path embedded in a receipt.
 # The PR377 source archive intentionally carries the source work tree while
 # the package proof pins the fresh CPython-3.12 receipts.  Overlay those
 # receipts only after the strict source replay above, so the replay's own
 # manifest remains exact.
 cproof=ext/'pr377-source/nine-stage-complex-e8'
 shutil.copy(pkg/'proof/complex/cp312/VERIFICATION.json',cproof/'VERIFICATION.json')
 shutil.copytree(pkg/'proof/complex/cp312/work',cproof/'work',dirs_exist_ok=True)
 assembled=work/'ASSEMBLY.json'
 assemble=pkg/'code/assemble.py'
 run('exact-assembly',[assemble,'--parent',ext/'pr376-source/research/e8-bit-seven-stage','--priced',pkg/'proof/price/kappa.json','--finite',pkg/'proof/finite.json','--complex-proof',ext/'pr377-source/nine-stage-complex-e8','--output',assembled],work,logs)
 assert assembled.read_bytes()==(pkg/'proof/assembly/ASSEMBLY.json').read_bytes()
 exact=read(assembled);assert exact['kappa']=='124243257674225949446409/125000000000000000000000000';assert exact['adjacent_grid_rejected'] and exact['complex_leaf_cap_rejected']
 checks.append('exact-assembly-byte-equality')
 out=dict(status='PASS_PORTABLE_E8_SEVEN_NINE_VERIFY',checks=checks,quick=a.quick,work=str(work),candidate_sha256=sha(croot/'candidate-word.json.gz'),kappa=k)
 (work/'VERIFICATION.json').write_text(json.dumps(out,indent=2,sort_keys=True)+'\n');print(out['status'],flush=True)

def read_json_gz(p): return json.loads(gzip.decompress(Path(p).read_bytes()))
if __name__=='__main__':main()
