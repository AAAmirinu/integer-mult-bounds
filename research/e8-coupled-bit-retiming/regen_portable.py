"""Run immutable Sussman generators with canonical LF text and portable paths.

The generated Lean/JSON text is normalized from CRLF to LF on Windows before
exact byte comparison. Frozen source files and numerical data are unchanged.
"""
from pathlib import Path
import tempfile,subprocess,os,sys,hashlib
def main():
    script=Path(sys.argv[1]).resolve();root=script.parents[2]
    with tempfile.TemporaryDirectory(prefix='e8-portable-regeneration-') as td:
        out=Path(td);env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1',GX_OUT=td)
        for args in [('tools/gx/gxgen.py','tools/certificate/gcert1-e8-r783.json.gz','E8'),('tools/gx/gxrate.py','B2Ge8','E8')]:
            runner=Path(__file__).with_name('run_pinned.py')
            subprocess.run([sys.executable,'-B',str(runner),*args],cwd=root,env=env,check=True)
        same=extra=0
        for file in sorted(out.rglob('*')):
            if not file.is_file():continue
            rel=file.relative_to(out)
            if rel.parts[0]=='logs':continue
            target=root/('comparator' if rel.parts[0]=='cmp' else rel.parts[0])
            target=target.joinpath(*rel.parts[1:])
            if not target.is_file():extra+=1;continue
            original=target.read_bytes();generated=file.read_bytes().replace(b'\r\n',b'\n')
            if generated!=original:
                import difflib
                diff=''.join(difflib.unified_diff(original.decode('utf-8').splitlines(True),generated.decode('utf-8').splitlines(True),fromfile='pinned',tofile='generated'))
                print(diff[:6000],file=sys.stderr)
                raise ValueError(f'Canonical regenerated bytes differ: {rel.as_posix()}')
            same+=1
        if (same,extra)!=(25,3):raise ValueError(f'Unexpected regeneration coverage: {(same,extra)}')
        print('Portable adapter: canonical LF generated bytes and native relative paths; all 25 source files unchanged.')
        print('RESULT: REPRODUCED (25 repository files reproduced byte for byte, 0 different, 3 generated files not in the repository)')
if __name__=='__main__':main()
