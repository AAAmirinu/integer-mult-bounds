"""PR #425's mutable-basis word (jacklightChen / Zhihao Chen): Thms A, B, C and Theorem S, checked exactly.

Input: inputs/pr425/FULL-WORD.json.gz = #425's FULL-WORD.json.gz (920 registers: 120 sources, 120 targets, 680 helper
registers), regenerated by #425's own hamming_packets.py + hamming_full.py; sha256 equals #425's EXPECTED.json.
Events: ['add', t, s, num, den, frame] (t += (num/den) s with both at 'frame'; frame None marks the centre copy that
drops full -> 0) and ['scale', t, num, den, frame].  Phases: A, cut (8 centre copies), B, cleanup (at the full frame).

(1) frame + taint replay on the word as written. Thm A (taint of each gate register inside the gate frame), Cor A1
    (target taint orthogonal to its port, target frames inside the hyperplane), no target feeds a z-register
    (z = sources + helpers), nested climbs, every gate at one common frame. The same detector, run in 'immutable'
    mode, counts the two things the immutable-source / no-target-read format forbids.
    Thm C on the 8 centre copies (pairing ranks vs frames paid). Thm B data (neighbourhood rank of every target) and
    the common cut (all targets at frame 0 at the scatter).
(2) exact scalar replay over Q: z restored, J = I, V and K; with the frame-0 preconditioner y <- V^-1 (y - K s) the
    word is exactly (x, s, y) -> (x, s, y + x). Control: omitting the K part is rejected.
(3) Theorem S: the conversion to the immutable-source / no-target-read format with one helper per modified source and
    one per read target. Replayed with the same detector (zero violations) and exactly over Q (after the frame-0
    compensation of the response to the dirty registers). Controls: the same detector flags the unconverted word;
    without the compensation the converted word is not (x, s, y) -> (x, s, y + x).
(4) coarse price (the moment of #425's hamming_full.py) of the word and of the converted word.
"""
import copy
import gzip
import json
import sys
from collections import Counter, defaultdict
from fractions import Fraction as Q
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "checks"))
from f2 import pairing_rank, par  # noqa: E402

V = 120


def basis(vectors):
    """Reduced echelon basis (tuple, descending pivots) of the F_2 span of ints."""
    b = {}
    for x in vectors:
        for p in sorted(b, reverse=True):
            if x >> p & 1:
                x ^= b[p]
        if x:
            p = x.bit_length() - 1
            for q in b:
                if b[q] >> p & 1:
                    b[q] ^= x
            b[p] = x
    return tuple(b[p] for p in sorted(b, reverse=True))


def inside(a, b):
    return basis(list(a) + list(b)) == tuple(b) if b else not a


def perp(p, F):
    return all(par(p & x) == 0 for x in F)


def hyper(p):
    return basis([x for x in range(1, 512) if par(x & p) == 0])


FULL = basis([1 << i for i in range(9)])


def is_tgt(r):
    return V <= r < 2 * V


def frame_replay(phases, n, P, immutable, final_frames=True, collect=None):
    """phases: [(name, events)]. Returns (cur, taint, kids, viol, stats)."""
    cur = [((P[r],) if r < V else ()) for r in range(n)]
    taint = [((P[r],) if r < V else ()) for r in range(n)]
    kids = defaultdict(list)
    viol, stats = Counter(), Counter()

    def climb(r, F):
        if not inside(cur[r], F):
            viol["non-nested"] += 1
        dr = len(F) - len(cur[r])
        if dr:
            kids[r].append(dr)
        cur[r] = F

    for ph, evs in phases:
        if ph == "cut" and collect is not None:
            collect["frames_at_cut"] = {r: cur[r] for r in range(n)}
        for e in evs:
            if e[0] == "scale":
                t = e[1]
                F = tuple(e[4]) if e[4] is not None else cur[t]
                climb(t, F)
                stats["scale"] += 1
                if t < V:
                    stats["src_modified"] += 1
                    if immutable:
                        viol["source modified"] += 1
                continue
            _, t, s = e[:3]
            F = e[5]
            if F is None:                       # centre copy: drop full -> 0, the target must stand at frame 0
                if cur[t] != ():
                    viol["cut-target-not-at-0"] += 1
                stats["cut"] += 1
                continue
            F = tuple(F)
            climb(t, F)
            climb(s, F)
            if is_tgt(s) and not is_tgt(t):
                viol["target-feeds-z"] += 1
            if is_tgt(s):
                stats["target_read"] += 1
                if immutable:
                    viol["target read"] += 1
            if t < V:
                stats["src_modified"] += 1
                if immutable:
                    viol["source modified"] += 1
            taint[t] = basis(list(taint[t]) + list(taint[s]))
            for r in (t, s):
                if not inside(taint[r], cur[r]):
                    viol["ThmA taint not in frame"] += 1
                if is_tgt(r):
                    if not perp(P[r - V], cur[r]):
                        viol["target frame not in hyperplane"] += 1
                    if not perp(P[r - V], taint[r]):
                        viol["CorA1 target taint not perp"] += 1
        if ph == "B" and final_frames:
            for r in range(n):
                climb(r, hyper(P[r - V]) if is_tgt(r) else FULL)
    return cur, taint, kids, viol, stats


def scalar_replay(evs, n, rows=None):
    rows = rows if rows is not None else [{r: Q(1)} for r in range(n)]
    for e in evs:
        if e[0] == "scale":
            q = Q(e[2], e[3])
            rows[e[1]] = {j: q * x for j, x in rows[e[1]].items()}
            continue
        t, s, q = e[1], e[2], Q(e[3], e[4])
        for j, x in list(rows[s].items()):
            z = rows[t].get(j, Q(0)) + q * x
            if z:
                rows[t][j] = z
            else:
                rows[t].pop(j, None)
    return rows


def inv_mat(M):
    idx = sorted(M)
    k = len(idx)
    pos = {r: i for i, r in enumerate(idx)}
    a = [[M[r].get(c, Q(0)) for c in idx] + [Q(int(i == j)) for j in range(k)] for i, r in enumerate(idx)]
    for col in range(k):
        piv = next(i for i in range(col, k) if a[i][col])
        a[col], a[piv] = a[piv], a[col]
        q = a[col][col]
        a[col] = [x / q for x in a[col]]
        for i in range(k):
            if i != col and a[i][col]:
                f = a[i][col]
                a[i] = [x - f * y for x, y in zip(a[i], a[col])]
    return {r: {c: a[pos[r]][k + pos[c]] for c in idx if a[pos[r]][k + pos[c]]} for r in idx}


def price(local, Rc, m=73, T=8, L=9):
    """Coarse complex price of hamming_full.py: root of the moment sum (floats, 80 bisections)."""
    W = 7680 + L * Rc
    g = Counter({r: z * L * T for r, z in local.items()})
    for r in (16, 8, 32, 8, 48, 8, 48, 32, 16):
        g[r] += 240 * T
    g[1] += L * Rc
    N = sum(g.values())
    lo, hi = 0., .003
    for _ in range(80):
        q = (lo + hi) / 2
        mom = sum(r * z / (m * W) * (m / r) ** q for r, z in g.items()) + 32 * m * N / (10 ** 16 * W) * m ** q
        if mom < 1:
            lo = q
        else:
            hi = q
    return (lo + hi) / 2


def local_hist(kids):
    H = Counter()
    for r, ks in kids.items():
        for d in ks:
            H[d] += 1
    H[9] += 8      # centre copies
    return H


def run():
    WD = json.load(gzip.open(ROOT / "inputs" / "pr425" / "FULL-WORD.json.gz"))
    P, Rr = WD["ports"], WD["root_lines"]
    assert len(P) == V and all(par(q) for q in P)
    A, B, CUT, CLEAN = WD["A"], WD["B"], WD["cut"], WD["cleanup"]
    n = 1 + max(max(e[1], e[2] if e[0] == "add" else 0) for e in A + B + CUT + CLEAN)
    R0 = n - 2 * V
    centers = WD["centers"]
    out = dict(registers=n, helpers=R0, m=WD["report"]["m"], h=WD["report"]["h"], v=WD["report"]["v"])
    assert (n, R0, out["m"], out["h"]) == (920, 680, 73, 9)
    # the ports are an admissible E8 labelling in the sense of sat_e8 (u.u = 1, orthogonal on the 3,360 non-orthogonal
    # root pairs, Gram 1 on the 3,780 orthogonal pairs), with the word's own root_lines: by the uniqueness result
    # of sat_e8.uniqueness_h9 it is Sussman's labelling up to isometry
    ip = lambda a, b: sum(int(x) * int(y) for x, y in zip(a, b)) // 2     # noqa: E731
    assert all(sum(int(x) * int(x) for x in Rr[s]) == 4 for s in range(V))
    gram_ok = all(bin(P[s] & P[t]).count("1") % 2 == (1 if s == t else (1 + ip(Rr[s], Rr[t])) % 2)
                  for s in range(V) for t in range(V))
    assert gram_ok
    out["ports_realise_E8_gram"] = gram_ok

    # ---- (1) frame + taint replay, Thm A, Cor A1, Thm B data, Thm C on the centres
    cleanFULL = [[e[0], *e[1:-1], list(FULL)] for e in CLEAN]
    phases = [("A", A), ("cut", CUT), ("B", B), ("clean", cleanFULL)]
    coll = {}
    cur, taint, kids, viol, stats = frame_replay(phases, n, P, immutable=False, collect=coll)
    assert not viol, dict(viol)
    _, _, _, viol_imm, stats_imm = frame_replay(phases, n, P, immutable=True)
    out["detector_on_word_as_written"] = dict(sorted(viol_imm.items()))
    assert viol_imm == Counter({"source modified": 1640, "target read": 112}), dict(viol_imm)
    modsrc = sorted({e[1] for e in A + B if e[1] < V})
    readtg = sorted({e[2] for e in A + B if e[0] == "add" and is_tgt(e[2])})
    out.update(thmA_violations=0, modified_sources=len(modsrc), read_targets=len(readtg),
               stats={k: stats[k] for k in ("scale", "cut", "src_modified", "target_read")})
    assert (len(modsrc), len(readtg)) == (112, 112)
    # common cut (R2 of Thm B): every target stands at frame 0 at the scatter
    at_cut = coll["frames_at_cut"]
    out["all_targets_at_frame0_at_cut"] = all(at_cut[V + t] == () for t in range(V))
    assert out["all_targets_at_frame0_at_cut"]
    # Thm B data: lossless set of each target = final taint; its rank (= h-1 means N = q^perp)
    nr = sorted({len(taint[V + t]) for t in range(V)})
    out["target_neighbourhood_ranks"] = nr
    assert nr == [8] and all(perp(P[t], taint[V + t]) for t in range(V))
    assert all(len(basis(list(taint[V + t]) + [P[t]])) == 9 for t in range(V))     # q_t is not in its own lossless span
    out["m_min_nine_stages"] = 1 + 9 * max(nr)
    assert out["m_min_nine_stages"] == out["m"] == 73
    # Thm C on the eight centre copies: pairing rank of (sources gathered drop-free into the centre before the cut)
    # x (targets reading it) against the frames paid. The gathered sources come from a bit-set taint replay of phase A
    # and must equal the support of the centre's root-line coordinate.
    tm = [(1 << r) if r < V else 0 for r in range(n)]
    for e in A:
        if e[0] == "add":
            tm[e[1]] |= tm[e[2]]
    cst_bound = cst_paid = 0
    gathered = []
    for i, c in enumerate(centers):
        srcs = [s for s in range(V) if tm[c] >> s & 1]
        assert srcs == [s for s in range(V) if int(Rr[s][i]) != 0], "centre taint differs from its root-line support"
        assert basis([P[s] for s in srcs]) == coll["frames_at_cut"][c], "sources do not span the centre's frame"
        readers = sorted({e[1] - V for e in CUT if e[2] == c})
        cst_bound += pairing_rank([P[s] for s in srcs], [P[t] for t in readers])
        cst_paid += len(coll["frames_at_cut"][c])
        gathered.append(len(srcs))
    out["sources_gathered_per_centre"] = gathered
    out.update(cst_bound=cst_bound, cst_paid=cst_paid)
    assert cst_bound == cst_paid == WD["report"]["cst"] == 72

    # ---- (2) exact scalar replay
    rows = scalar_replay(A + CUT + B + CLEAN, n)
    zok = all(rows[r] == {r: Q(1)} for r in range(n) if not is_tgt(r))
    J_ok = all({j: x for j, x in rows[V + t].items() if j < V} == {t: Q(1)} for t in range(V))
    Vnon = sum(1 for t in range(V) for j, x in rows[V + t].items() if is_tgt(j) and j != V + t)
    Knz = sum(1 for t in range(V) for j in rows[V + t] if j >= 2 * V)
    Vm = {V + t: {j: x for j, x in rows[V + t].items() if is_tgt(j)} for t in range(V)}
    Vi = inv_mat(Vm)
    pre_rows = []
    for t in range(V):
        row = dict(Vi[V + t])
        for u, a in Vi[V + t].items():
            for j, x in rows[u].items():
                if j >= 2 * V:
                    row[j] = row.get(j, Q(0)) - a * x
        pre_rows.append({j: x for j, x in row.items() if x})
    init = [{r: Q(1)} for r in range(n)]
    for t in range(V):
        init[V + t] = pre_rows[t]
    rows2 = scalar_replay(A + CUT + B + CLEAN, n, init)
    ok2 = all(rows2[r] == {r: Q(1)} for r in range(n) if not is_tgt(r)) and \
        all(rows2[V + t] == {V + t: Q(1), t: Q(1)} for t in range(V))
    init3 = [{r: Q(1)} for r in range(n)]
    for t in range(V):
        init3[V + t] = dict(Vi[V + t])
    rows3 = scalar_replay(A + CUT + B + CLEAN, n, init3)
    neg = any(rows3[V + t] != {V + t: Q(1), t: Q(1)} for t in range(V))
    out.update(z_restored=zok, J_is_identity=J_ok, V_offdiag=Vnon, K_nonzeros=Knz,
               preconditioned_map_exact=ok2, omit_K_control_rejected=neg)
    assert zok and J_ok and ok2 and neg

    # ---- (3) Theorem S
    sim, nn = {}, n
    for r in modsrc + readtg:
        sim[r] = nn
        nn += 1

    def ren(e):
        e = list(e)
        e[1] = sim.get(e[1], e[1])
        if e[0] == "add":
            e[2] = sim.get(e[2], e[2])
        return e

    pre = [["add", sim[r], r, 1, 1, [P[r]]] for r in modsrc]
    A1, C1, B1 = [ren(e) for e in A], [ren(e) for e in CUT], [ren(e) for e in B]
    final = [["add", t, sim[t], 1, 1, list(hyper(P[t - V]))] for t in readtg]
    fwd_z = [e for e in pre + A1 + C1 + B1 if not is_tgt(e[1])][len(pre):]

    def inv(e):
        e = copy.deepcopy(e)
        if e[0] == "add":
            e[3] = -e[3]
            e[5] = list(FULL)
        else:
            e[2], e[3] = e[3], e[2]
            e[4] = list(FULL)
        return e

    clean1 = [inv(e) for e in reversed(fwd_z)] + [["add", sim[r], r, -1, 1, list(FULL)] for r in modsrc]
    phasesS = [("A", pre + A1), ("cut", C1), ("B", B1 + final), ("clean", clean1)]
    # the same detector on the converted word; the converted targets g_t must stay inside their hyperplane
    # (the detector checks real targets; g_t is a helper, checked separately below)
    # g_t follows y_t's frames; the final gate y_t += g_t is at hyper(P_t), so the detector's nestedness test also
    # checks that g_t stands inside the hyperplane at that time
    curS, taintS, kidsS, violS, statsS = frame_replay(phasesS, nn, P, immutable=True, final_frames=True)
    out["detector_on_converted_word"] = dict(sorted(violS.items()))
    assert not violS, dict(violS)
    rowsS = scalar_replay(pre + A1 + C1 + B1 + final + clean1, nn)
    zS = all(rowsS[r] == {r: Q(1)} for r in range(nn) if not is_tgt(r))
    KS = sum(1 for t in range(V) for j in rowsS[V + t] if j >= 2 * V)
    initS = [{r: Q(1)} for r in range(nn)]
    for t in range(V):
        initS[V + t] = {V + t: Q(1)}
        for j, x in rowsS[V + t].items():
            if j >= 2 * V:
                initS[V + t][j] = -x
    rowsS2 = scalar_replay(pre + A1 + C1 + B1 + final + clean1, nn, initS)
    okS = all(rowsS2[r] == {r: Q(1)} for r in range(nn) if not is_tgt(r)) and \
        all(rowsS2[V + t] == {V + t: Q(1), t: Q(1)} for t in range(V))
    negS = any(rowsS[V + t] != {V + t: Q(1), t: Q(1)} for t in range(V))      # without the frame-0 compensation
    RS = nn - 2 * V
    out.update(S_helpers=RS, S_helpers_formula="R + b_x + b_y", S_z_restored=zS, S_K_nonzeros=KS,
               S_exact_after_compensation=okS, S_uncompensated_rejected=negS)
    assert RS == R0 + len(modsrc) + len(readtg) == 904 and zS and okS and negS

    # ---- (4) coarse price
    H0 = local_hist(kids)
    b0 = price(H0, R0)
    HS = local_hist(kidsS)
    bS = price(HS, RS)
    rep = WD["report"]
    assert abs(b0 - rep["complex_coarse_float"]) < 1e-15
    out.update(local_hist={str(k): v for k, v in sorted(H0.items())}, mass=sum(r * z for r, z in H0.items()),
               b=b0, b_pre425=rep["baseline_b"], S_local_hist={str(k): v for k, v in sorted(HS.items())},
               S_mass=sum(r * z for r, z in HS.items()), S_b=bS, S_b_vs_b_percent=round(100 * (bS / b0 - 1), 2))
    return out
